/**
 * PKCE for the sign-in link (RFC 7636, S256). Server actions have
 * `crypto.getRandomValues` but no `crypto.subtle`, so the SHA-256 the
 * challenge needs is computed here (FIPS 180-4), on ASCII input only: the
 * verifier is base64url text.
 */

